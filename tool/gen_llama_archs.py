#!/usr/bin/env python3
"""Regenerates lib/utils/llama_archs.dart from the bundled llama.cpp.

Run after updating the llama.cpp submodule:  python3 tool/gen_llama_archs.py
"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'local_plugins/llama_flutter_android/android/src/main/cpp/llama.cpp/src/llama-arch.cpp').read_text()
i = src.index('LLM_ARCH_NAMES'); j = src.index('};', i)
names = re.findall(r'\{\s*LLM_ARCH_[A-Z0-9_]+\s*,\s*"([^"]+)"\s*\}', src[i:j])
# Architectures that load but are not chat/text-generation models for this app
# (embedding encoders, audio codecs, speculative-draft heads, diffusion LMs).
not_chat = {
    'clip', '(unknown)', 'bert', 'modern-bert', 'nomic-bert', 'nomic-bert-moe',
    'neo-bert', 'jina-bert-v2', 'jina-bert-v3', 'eurobert', 'gemma-embedding',
    'llama-embed', 't5', 't5encoder', 'wavtokenizer-dec', 'qwen3tts',
    'pockettts', 'eagle3', 'dflash', 'gemma4-assistant', 'dream', 'llada',
    'llada-moe', 'rnd1',
}
chat = sorted(n for n in names if n not in not_chat)
out = ["// GENERATED by tool/gen_llama_archs.py - do not edit by hand.",
       "// Text-generation architectures the bundled llama.cpp can run.",
       "const Set<String> kLlamaChatArchitectures = {"]
out += [f"  '{n}'," for n in chat]
out += ["};", "",
        "/// True when a GGUF with this `general.architecture` can run here.",
        "/// Unknown (null/empty) is treated as supported so we never hide a",
        "/// model just because Hugging Face has no metadata for it.",
        "bool isSupportedLlamaArch(String? arch) =>",
        "    arch == null || arch.isEmpty || kLlamaChatArchitectures.contains(arch);", ""]
(root / 'lib/utils/llama_archs.dart').write_text("\n".join(out))
print(len(chat), 'architectures')
